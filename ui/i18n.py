def set_language(lang: str) -> str:
    """Set active display language ('en' default or 'id')."""
    global _ACTIVE_LANGUAGE
    norm = "id" if str(lang).strip().lower() == "id" else "en"
    _ACTIVE_LANGUAGE = norm
    return _ACTIVE_LANGUAGE


def get_language() -> str:
    """Return active language code ('en' or 'id')."""
    return _ACTIVE_LANGUAGE


def tr(msg_key: str, /, **kwargs: object) -> str:
    """Translate key in active language with safe fallback to English."""
    lang_map = _TRANSLATIONS.get(_ACTIVE_LANGUAGE, _TRANSLATIONS["en"])
    text = lang_map.get(msg_key)
    if text is None:
        text = _TRANSLATIONS["en"].get(msg_key, msg_key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
